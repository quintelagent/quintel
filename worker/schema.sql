-- Quintel D1 schema
CREATE TABLE IF NOT EXISTS prices (
  ts TEXT NOT NULL, source TEXT NOT NULL, price REAL NOT NULL,
  PRIMARY KEY (ts, source)
);
CREATE TABLE IF NOT EXISTS history_daily (
  date TEXT PRIMARY KEY, close REAL NOT NULL
);
CREATE TABLE IF NOT EXISTS news (
  id TEXT PRIMARY KEY, ts TEXT NOT NULL, title TEXT NOT NULL, url TEXT, source TEXT,
  relevant INTEGER, score REAL, category TEXT, one_line TEXT, triaged_at TEXT
);
CREATE INDEX IF NOT EXISTS news_ts ON news(ts);
CREATE TABLE IF NOT EXISTS runs (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  ts TEXT NOT NULL, session TEXT NOT NULL, seed TEXT NOT NULL,
  input_hash TEXT NOT NULL, output_hash TEXT NOT NULL,
  spot REAL NOT NULL, price_source TEXT NOT NULL, crisis INTEGER NOT NULL,
  cpu_ms INTEGER, summary TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS runs_ts ON runs(ts);
CREATE TABLE IF NOT EXISTS run_outputs (
  id INTEGER PRIMARY KEY, inputs TEXT NOT NULL, output TEXT NOT NULL, sample TEXT
);
CREATE TABLE IF NOT EXISTS briefings (
  id INTEGER PRIMARY KEY AUTOINCREMENT, ts TEXT NOT NULL, run_id INTEGER NOT NULL,
  body TEXT NOT NULL, hash TEXT NOT NULL, model TEXT, fallback INTEGER NOT NULL DEFAULT 0, attempts INTEGER
);
CREATE INDEX IF NOT EXISTS briefings_ts ON briefings(ts);
CREATE TABLE IF NOT EXISTS desk_positions (
  id INTEGER PRIMARY KEY CHECK (id = 1), state TEXT NOT NULL, hash TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS desk_trades (
  id INTEGER PRIMARY KEY AUTOINCREMENT, ts TEXT NOT NULL, run_id INTEGER NOT NULL,
  action TEXT NOT NULL, side TEXT NOT NULL, price REAL NOT NULL, qty REAL NOT NULL,
  pnl REAL, reason TEXT NOT NULL, note TEXT
);
CREATE TABLE IF NOT EXISTS desk_equity (
  ts TEXT PRIMARY KEY, run_id INTEGER NOT NULL, equity REAL NOT NULL, price REAL NOT NULL, state_hash TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS fingerprints (
  hour TEXT PRIMARY KEY, hash TEXT NOT NULL, payload TEXT NOT NULL, tx TEXT,
  status TEXT NOT NULL, attempts INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL, sent_at TEXT, error TEXT
);
CREATE TABLE IF NOT EXISTS scorecard (
  run_id INTEGER NOT NULL, horizon INTEGER NOT NULL, run_date TEXT NOT NULL, target_date TEXT NOT NULL,
  actual REAL NOT NULL, p5 REAL, p25 REAL, p75 REAL, p95 REAL, p_up REAL,
  in50 INTEGER NOT NULL, in90 INTEGER NOT NULL, brier REAL NOT NULL,
  PRIMARY KEY (run_id, horizon)
);
CREATE TABLE IF NOT EXISTS counters (
  key TEXT PRIMARY KEY, value INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS meta (
  key TEXT PRIMARY KEY, value TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS ai_usage (
  id INTEGER PRIMARY KEY AUTOINCREMENT, ts TEXT NOT NULL, day TEXT NOT NULL, purpose TEXT NOT NULL,
  model TEXT NOT NULL, tokens_in INTEGER, tokens_out INTEGER, cost_usd REAL NOT NULL, ok INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS ai_usage_day ON ai_usage(day);
